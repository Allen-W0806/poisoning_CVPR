"""Seal selected completed-run evidence for an integrity-checked local mirror.

Large checkpoints, model weights and poison tensors remain at their recorded
cluster paths. Raw responses, logs, source snapshots and assessment images are
included. No dataset, model or experiment is generated by this packaging step.
"""
import argparse
from datetime import datetime, timezone
import json
from pathlib import Path
import zipfile

ROOT = Path(__file__).resolve().parents[1]
import sys
sys.path.insert(0, str(ROOT))
from src.mini_pilot.data import sha256, write_json
from scripts.submit_reward_campaign import accounting


def main():
    p=argparse.ArgumentParser(__doc__)
    p.add_argument("--campaign",type=Path,required=True)
    p.add_argument("--phase",choices=["review","final"],default="final")
    args=p.parse_args();campaign=args.campaign.resolve()
    if not campaign.is_relative_to(ROOT/"outputs") or campaign==ROOT/"outputs":
        raise ValueError("Expected a run-specific canonical output")
    required=["internal_pilot/run_state.json", "shadowcast/verified_statistics.json",
              "vizwiz/verified_statistics.json", "lighting_vqa_audit/summary.json",
              "internal_pilot_raw_audit.json", "vizwiz/raw_score_audit.json"]
    for name in required:
        if not (campaign/name).is_file():raise ValueError("Required final evidence is absent: "+name)
    if json.loads((campaign/required[0]).read_text())["status"]!="COMPLETED":
        raise ValueError("Never seal an unfinished primary pilot as completed")
    acc=accounting(campaign)
    if not all(r["settled"] for r in acc["records"]) or acc["actual_GPU_seconds"]>72000:
        raise ValueError("All campaign GPU jobs must be settled within the authorized cap")
    write_json(campaign/"GPU_ACCOUNTING.json",acc)
    # Copyable text evidence includes the raw failed/cancelled run history.
    suffixes={".json",".jsonl",".md",".csv",".tex",".log",".sbatch",".sh",".py",".mjs",".txt",".pdf",".pptx"}
    manifest_name="SELECTED_DELIVERY_MANIFEST.json" if args.phase=="final" else "REVIEW_INPUT_MANIFEST.json"
    receipt_name="SELECTED_DELIVERY_RECEIPT.json" if args.phase=="final" else "REVIEW_INPUT_DELIVERY_RECEIPT.json"
    paths=[]
    for path in campaign.rglob("*"):
        if not path.is_file() or path.is_symlink():continue
        relative=path.relative_to(campaign)
        if "__pycache__" in relative.parts or path.name in {manifest_name,receipt_name}:continue
        keep=path.suffix in suffixes
        if path.suffix==".png":
            keep=(relative.parts[0] in {"diagnostics","figures"} or
                  (relative.parts[0]=="internal_pilot" and
                   ("sources" in relative.parts or "assessment" in relative.parts)))
        if keep:paths.append(path)
    entries=[{"path":str(p.relative_to(campaign)),"bytes":p.stat().st_size,"SHA256":sha256(p)} for p in sorted(paths)]
    retained=[]
    for path in campaign.rglob("*"):
        if path.is_file() and path.suffix in {".pt",".bin",".safetensors"}:
            retained.append({"path":str(path),"bytes":path.stat().st_size,"SHA256":sha256(path)})
    manifest={"UTC":datetime.now(timezone.utc).isoformat(),"source_root":str(campaign),"delivery_phase":args.phase,
              "included":entries,"included_bytes":sum(r["bytes"] for r in entries),
              "large_evidence_retained_on_cluster":retained,"model_weights_copied":False,
              "GPU_accounting":acc,"scope":"selected delivery mirror, not a claim that omitted large evidence was copied"}
    write_json(campaign/manifest_name,manifest)
    scratch=(ROOT/"tmp"/(campaign.name+"_delivery")).resolve()
    if not scratch.is_relative_to(ROOT/"tmp"):raise ValueError("Scratch escaped intended project tmp")
    scratch.mkdir(exist_ok=True)
    archive=scratch/(args.phase+"_selected_evidence.zip")
    if archive.exists():raise FileExistsError("Do not overwrite a prior sealed delivery archive")
    with zipfile.ZipFile(archive,"x",compression=zipfile.ZIP_DEFLATED,compresslevel=1) as z:
        for path in paths:z.write(path,str(path.relative_to(campaign)))
        z.write(campaign/manifest_name,manifest_name)
    receipt={"archive":str(archive),"bytes":archive.stat().st_size,"SHA256":sha256(archive),
             "manifest_path":manifest_name,"manifest_SHA256":sha256(campaign/manifest_name),"files":len(entries)}
    write_json(campaign/receipt_name,receipt)
    print(json.dumps(receipt,indent=2))


if __name__=="__main__":main()
